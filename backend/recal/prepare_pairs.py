"""Create private runtime pairs from declared Ross manual evidence, never vendor it."""
import hashlib,json,re
from pathlib import Path

# Search spans identify facts for manual review, not class-specific prompt cues.
RECIPES=[
 ('calibration','atf-wiki/Topics/Calibration.md',r'Calibration must be run after every physical restart of the arm\.',
  'After a physical restart, run calibration before drawing.',
  ['What setup step is required after a physical restart?','The arm has been restarted. What does the manual require first?','According to the manual, what follows a physical restart before drawing?']),
 ('port','skills/huenit/SKILL.md',r'The `HUENIT_PORT` environment variable overrides the auto-detected port\.',
  'Use the HUENIT_PORT environment variable to override automatic port selection.',
  ['How can I override automatic serial port selection?','Which setting replaces the auto-detected arm port?','What documented option lets me choose the arm port explicitly?']),
 ('pressure','COMMANDS.md',r'Pen too light \| Adjust Z_DOWN lower in calibration',
  'For a pen drawing too lightly, adjust Z_DOWN lower in calibration.',
  ['What adjustment does the troubleshooting table suggest for a light pen?','The pen marks are too light. What does the manual recommend?','Which documented calibration adjustment addresses insufficient pen contact?']),
 ('approval','COMMANDS.md',r'approve Confirm and draw the last image/sketch preview cancel Discard the pending preview',
  'Use approve to confirm the preview, or cancel to discard it.',
  ['How do I confirm or discard the pending preview?','What documented actions accept or reject the last sketch preview?','Which two commands control whether a preview gets drawn or discarded?']),
 ('locking','atf-wiki/Subsystems/JobOrchestration.md',r'Uses `/tmp/robot_ross_running.lock` to ensure only one job runs at a time\.',
  'The /tmp/robot_ross_running.lock job lock prevents concurrent jobs.',
  ['What prevents two drawing jobs from running at once?','Which documented mechanism enforces one job at a time?','How does the orchestrator prevent concurrent drawing jobs?']),
 ('narration','skills/robot-ross/SKILL.md',r'`--no-voice`[^\n]{0,50}?silent draw \(no narration\)',
  'Use the --no-voice flag to request a silent drawing without narration.',
  ['What flag requests a silent drawing without narration?','How does the manual say to disable drawing narration?','Which option turns off voice commentary for a drawing job?'])
]


def prepare(evidence_file, output):
    raw=Path(evidence_file).read_bytes();chunks=[p for group in json.loads(raw) for p in group]
    supports=[]
    for topic,source,pattern,candidate,qs in RECIPES:
        hits=[(p,re.search(pattern,p['text'])) for p in chunks if p['source']==source and re.search(pattern,p['text'])]
        if not hits:raise ValueError('Missing exact reviewed support for '+topic)
        p,m=hits[0];quote=m.group(0)
        supports.append((p,quote))
    # Negative passages are separately reviewed unrelated descriptions from the
    # manual cache, never selected from model scores or generated by the model.
    controls=[
      'takes text prompts, SVG files, or spoken requests',
      'Commentary is spoken in parallel with the arm movements.',
      'OBS recording is optional; YouTube upload requires an explicit `--upload` command-line flag.',
      'The Z-height for pen-up (`Z_UP=6.0mm`) and pen-down is established.',
      'The system follows a three-layer architecture:',
      'The Video URL column is also read back by `artist_poller.py`'
    ]
    records=[];sources=[]
    for i,((topic,source,pattern,candidate,questions),(p,support)) in enumerate(zip(RECIPES,supports)):
        control=controls[i]
        cs=next((x for x in chunks if control in x['text']),None)
        if cs is None:raise ValueError('Control not an exact source span: '+topic)
        fold=('fit','validation','test')[i//2]
        sources.append({'group':topic,'fold':fold,'source':source,'source_sha256':p['source_sha256'],
          'support_span_sha256':hashlib.sha256(support.encode()).hexdigest(),'control_source':cs['source'],
          'control_span_sha256':hashlib.sha256(control.encode()).hexdigest()})
        for qi,q in enumerate(questions):
            pair=f'{topic}-{qi}'
            for supported,context in [(True,support),(False,control)]:
                text='Read the supplied manual excerpt and assess the candidate step.\nManual excerpt: '+context+'\nQuestion: '+q
                records.append({'id':pair+('-support' if supported else '-control'),'pair_id':pair,'group':topic,'fold':fold,
                  'supported':supported,'question':q,'candidate':candidate,'text':text})
    from paired_analysis import validate_records
    validate_records(records)
    payload={'protocol':'paired-footing-v1','records':records,'sources':sources,
       'cache_sha256':hashlib.sha256(raw).hexdigest(),'case_origin':'new in-event authored questions, exact spans from existing Ross manual snapshot; not a copied evaluation matrix',
       'method_reference':'Canis disposition paper draft section3, conceptual reference only; no code/vectors/data imported',
       'author_review':'Codi (agent) checked each exact support span/candidate/control; independent human review pending.',
       'labels':'supplied-context support; no generated-answer correctness claim', 'image_input':False}
    dest=Path(output);dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(json.dumps(payload,indent=2));dest.chmod(0o600)
    print('Frozen pairs:',dest,'records:',len(records),'sha256:',hashlib.sha256(dest.read_bytes()).hexdigest())
    for (topic,*_),(_,span) in zip(RECIPES,supports):print(topic,repr(span))

if __name__=='__main__':
    import sys
    prepare(sys.argv[1],sys.argv[2])
